void LCD_FillArea(uint16_t x, uint16_t y,
                  uint16_t w, uint16_t h, uint16_t color)
{
    uint32_t cnt;
    uint8_t hi, lo;
    uint16_t xend, yend;

    if (w == 0 || h == 0) return;
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;

    xend = (uint16_t)(x + w - 1);
    yend = (uint16_t)(y + h - 1);
    if (xend >= LCD_WIDTH)  xend = LCD_WIDTH  - 1;    
    if (yend >= LCD_HEIGHT) yend = LCD_HEIGHT - 1;    

    hi = (uint8_t)(color >> 8);
    lo = (uint8_t)(color & 0xFF);

    set_window(x, y, xend, yend);
    ram_start();
    for (cnt = (uint32_t)(xend - x + 1) * (uint32_t)(yend - y + 1);
         cnt != 0; cnt--) {
        spi_write_const(hi);
        spi_write_const(lo);
    }
    ram_end();
}

/* ============================================================================
 * 摄像头链路专用：把一行 RGB565（高字节在前）写入指定 y 行。
 * 每行单独开窗，即使上一包丢了也不会把画面写串位。
 * ========================================================================== */
static void spi_write_bytes_fast(const uint8_t *data, uint32_t len)
{
    uint32_t i;

    for (i = 0; i < len; i++) {
        while (!(LCD_SPI->SR & (1UL << 1))) {   /* 等 TXE */
        }
        *(volatile uint8_t *)&LCD_SPI->DR = data[i];
    }
}

void LCD_DrawRGB565Row(uint16_t x, uint16_t y, uint16_t w, const uint8_t *data)
{
    if (data == 0 || w == 0 || x >= LCD_WIDTH || y >= LCD_HEIGHT) return;

    if ((uint32_t)x + w > LCD_WIDTH) {
        w = (uint16_t)(LCD_WIDTH - x);
    }

    set_window(x, y, (uint16_t)(x + w - 1), y);
    ram_start();
    spi_write_bytes_fast(data, (uint32_t)w * 2u);
    ram_end();
}

 
void LCD_ShowImage256(uint16_t x, uint16_t y,
                      uint16_t w, uint16_t h,
                      const uint16_t *palette, const uint8_t *img)
{
    uint32_t i, total;
    uint16_t color;

    if (img == 0 || palette == 0 || w == 0 || h == 0) return;
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;

    if ((uint32_t)x + w > LCD_WIDTH)  w = (uint16_t)(LCD_WIDTH  - x);   
    if ((uint32_t)y + h > LCD_HEIGHT) h = (uint16_t)(LCD_HEIGHT - y);   

    set_window(x, y, (uint16_t)(x + w - 1), (uint16_t)(y + h - 1));
    ram_start();
    total = (uint32_t)w * h;
    for (i = 0; i < total; i++) {
        color = palette[img[i]];                     
        spi_write_byte((uint8_t)(color >> 8));       
        spi_write_byte((uint8_t)(color & 0xFF));     
    }
    ram_end();
}

 
