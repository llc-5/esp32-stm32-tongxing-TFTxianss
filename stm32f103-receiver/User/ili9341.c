static void delay_ms(uint32_t ms)
{
    volatile uint32_t i;

    while (ms--) {
        for (i = 0; i < 8000U; i++) {
             
        }
    }
}

/* ============================================================================
 * 底层字节发送：硬件 SPI1（PA5=SCK / PA7=MOSI）
 *
 * 原来这里是一位位翻转 GPIO 模拟 SPI，实测写一行 480 字节约 1.6ms、
 * 一帧 240 行要 390ms，是刷新率最大的瓶颈（比通讯本身还慢）。
 * PA5/PA7 本来就是 SPI1 的默认复用脚，改成硬件 SPI1 @18MHz 后
 * 同样 480 字节只要约 0.21ms，快 7~8 倍。
 *
 * CS/DC/RES 仍是普通 GPIO 软件控制：一包里要中途切 DC，软件管更方便。
 * ========================================================================== */
static void lcd_spi_init(void)
{
    LCD_RCC_APB2ENR |= (1UL << 12);          /* SPI1EN —— 原代码反而在清这一位 */

    LCD_SPI->CR1 = 0;
    LCD_SPI->CR2 = 0;
    LCD_SPI->I2SCFGR = 0;                    /* 选 SPI 模式，不是 I2S */
    /* MSTR=1 主机, SSM=1+SSI=1（NSS 不用硬件，CS 当普通 IO 软件拉）,
     * CPOL=0 CPHA=0（mode 0，和 ILI9341 一致）, DFF=0(8bit), MSB first,
     * BR=LCD_SPI_BR, SPE=1 */
    LCD_SPI->CR1 = (1UL << 2)                /* MSTR  */
                 | (1UL << 9)                /* SSM   */
                 | (1UL << 8)                /* SSI   */
                 | ((uint32_t)LCD_SPI_BR << 3)
                 | (1UL << 6);               /* SPE   */
}

/* 发一个字节，不等待发送结束（攒着发更快） */
static inline void lcd_spi_tx(uint8_t dat)
{
    while (!(LCD_SPI->SR & (1UL << 1))) {    /* 等 TXE：发送寄存器空 */
    }
    *(volatile uint8_t *)&LCD_SPI->DR = dat;
}

/* 等最后一个字节真正移出（BSY 清零），CS 才能拉高，否则会截掉尾巴 */
static void lcd_spi_flush(void)
{
    while (!(LCD_SPI->SR & (1UL << 1))) {    /* TXE */
    }
    while (LCD_SPI->SR & (1UL << 7)) {       /* BSY */
    }
}

/* 关片选：必须先等数据发完 */
static void lcd_cs_high(void)
{
    lcd_spi_flush();
    LCD_CS_H();
}

static void spi_write_byte(uint8_t dat)
{
    lcd_spi_tx(dat);
}

 
static void spi_write_const(uint8_t dat)
{
    lcd_spi_tx(dat);
}

static void write_cmd(uint8_t cmd)
{
    LCD_CS_L();
    LCD_DC_L();
    spi_write_byte(cmd);
    lcd_spi_flush();          /* 切 DC / 拉 CS 前必须等字节真正移出 */
    LCD_CS_H();
}

 
static void write_cmd_data(uint8_t cmd, const uint8_t *dat, uint8_t n)
{
    LCD_CS_L();
    LCD_DC_L();
    spi_write_byte(cmd);
    lcd_spi_flush();          /* 命令字节发完再切 DC，否则会被当成数据 */
    LCD_DC_H();
    while (n--) {
        spi_write_byte(*dat++);
    }
    lcd_cs_high();
}

static void ram_start(void)
{
    LCD_CS_L();
    LCD_DC_L();
    spi_write_byte(0x2C);
    lcd_spi_flush();          /* 0x2C 发完再切 DC */
    LCD_DC_H();
}

static void ram_end(void)
{
    lcd_cs_high();
}

static void set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
    uint8_t p[4];

    p[0] = (uint8_t)(x0 >> 8);
    p[1] = (uint8_t)(x0 & 0xFF);
    p[2] = (uint8_t)(x1 >> 8);
    p[3] = (uint8_t)(x1 & 0xFF);
    write_cmd_data(0x2A, p, 4);

    p[0] = (uint8_t)(y0 >> 8);
    p[1] = (uint8_t)(y0 & 0xFF);
    p[2] = (uint8_t)(y1 >> 8);
    p[3] = (uint8_t)(y1 & 0xFF);
    write_cmd_data(0x2B, p, 4);
}

 
static void gpio_init(void)
{
    uint32_t crl;

    LCD_RCC_APB2ENR |= (1UL << 2);           
    /* 原来这里有一句 &= ~(1<<12) 把 SPI1EN 关掉了，是历史遗留；
     * SPI1 现在给屏幕自己用，时钟在 lcd_spi_init() 里打开。 */

    crl  = LCD_GPIOA->CRL;
    crl &= ~((0xFUL << 0) | (0xFUL << 4) | (0xFUL << 8) |
             (0xFUL << 20) | (0xFUL << 28));
    /* PA0=RES PA1=CS PA2=DC 普通推挽输出(0x3)；
     * PA5=SCK PA7=MOSI 复用推挽输出(0xB)，交给 SPI1 硬件驱动 */
    crl |=  ((0x3UL << 0) | (0x3UL << 4) | (0x3UL << 8) |
             (0xBUL << 20) | (0xBUL << 28));
#if LCD_LED_CTRL
    crl &= ~(0xFUL << (4UL * LCD_LED_PIN));
    crl |=  (0x3UL << (4UL * LCD_LED_PIN));
#endif
    LCD_GPIOA->CRL = crl;

#if LCD_LED_CTRL
    LCD_LED_H();                             
#endif
    LCD_CS_H();                              
    LCD_RES_H();                              
    LCD_DC_H();
    /* SCK/SDI 已经是 SPI1 的复用脚，不用再手动拉电平 */
}

 
void LCD_Init(void)
{
    uint8_t p[4];

    gpio_init();
    lcd_spi_init();                          /* PA5/PA7 已配成复用，这里开硬件 SPI1 */
    LCD_RES_H();
    delay_ms(20);
    LCD_RES_L();
    delay_ms(20);
    LCD_RES_H();
    delay_ms(120);

    write_cmd(0x01);                         
    delay_ms(100);
    write_cmd(0x11);                         
    delay_ms(120);

     
    p[0] = 0x55;
    write_cmd_data(0x3A, p, 1);              
    p[0] = (uint8_t)LCD_MADCTL_VALUE;
    write_cmd_data(0x36, p, 1);              
    p[0] = 0x01;
    write_cmd_data(0x26, p, 1);              

#if LCD_USE_EXTENDED_INIT
    write_cmd_data(0xB1, INIT_B1, 2);        
    write_cmd_data(0xB6, INIT_B6, 3);        
    write_cmd_data(0xC0, INIT_C0, 1);        
    write_cmd_data(0xC1, INIT_C1, 1);        
    write_cmd_data(0xC5, INIT_C5, 2);        
    write_cmd_data(0xC7, INIT_C7, 1);        
    write_cmd_data(0xE0, INIT_E0, 15);
    write_cmd_data(0xE1, INIT_E1, 15);
#endif

    write_cmd(0x20);                         
    write_cmd(0x13);                         
    write_cmd(0x29);                         
    delay_ms(30);

    LCD_ClearScreen();                       
}

 
void LCD_Fill(uint16_t color)
{
    uint32_t i, total;
    uint8_t hi = (uint8_t)(color >> 8);
    uint8_t lo = (uint8_t)(color & 0xFF);

    total = (uint32_t)LCD_WIDTH * (uint32_t)LCD_HEIGHT;
    set_window(0, 0, LCD_WIDTH - 1, LCD_HEIGHT - 1);
    ram_start();
    for (i = 0; i < total; i++) {
        spi_write_const(hi);
        spi_write_const(lo);
    }
    ram_end();
}

 
static const uint8_t *get_glyph(char ch)
{
    if (ch >= '0' && ch <= '9') return FONT_8x16[ch - '0'];
    if (ch >= 'A' && ch <= 'Z') return FONT_UPPER[ch - 'A'];
    if (ch >= 'a' && ch <= 'z') return FONT_LOWER[ch - 'a'];
    return FONT_BLANK;
}

 
